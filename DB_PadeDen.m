    -(134543./7776 - 41./48.*pi.^2).*nu - 94403./3024.*nu.^2 - 775./324.*nu.^3;
    fl6   = -1712./105;
    f7    = -(16285./504 - 214745./1728.*nu - 193385./3024.*nu.^2).*pi;

    f4ss  = 0;
    X = linspace(0,0.1,100);
    A = linspace(0.95,1,100);
    [x,a]=meshgrid(X,A);
    figure
    grid on
    surface = sprintf('P_%d%d(x,a,f2,f3,f4,f5,f6,fl6,f7,@f3so,f4ss)',m,n);
    label = sprintf('(%d,%d)',m,n);

    surf(x,a,eval(surface),'DisplayName',label)
    hold on
    z = 0*x+0*a;
    surf(x,a,z,'DisplayName','$z=0$');

    lgd = legend('Location','northwest');
    lgd.FontSize = 25;
    set(lgd, 'Interpreter','latex')
    xlabel('$v$','Interpreter','latex','FontSize',20);
    ylabel('$a$','Interpreter','latex','FontSize',20);    
    zlabel('$\hat{f}$','Interpreter','latex','FontSize',20);
    %colorbar
    %hold off

return

