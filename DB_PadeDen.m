function DB_PadeDen(m,n)

%==========================================================================
% Look for zeros of the padé denominators varying a and v_omg
% Test mass
%==========================================================================
    q=0;

    nu         = q/(1+q).^2;
    eulergamma = 0.57721566490153286061;

    f2    = -1247./336 -35./12.*nu;
    f3    = 4.*pi;
    f4    = -44711./9072 + 9271./504.*nu + 65./18.*nu.^2;
    f5    = -(8191./672 + 583./24.*nu).*pi;
