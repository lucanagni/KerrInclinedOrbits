function [A,Bp,Bnp,Benp,Gs,dA,dBp,dBnp,dBenp,dGs] = DB_metric_Kerr(X,chi1)

%==========================================================================
% Kerr Cartesian metric
%==========================================================================

r = norm(X);
n = X./r;
a = norm(chi1);

% shorthands
r2 = r.^2;
u  = 1./r;
u3 = u.^3;
u4 = u.^4;
a2 = a.^2;
a4 = a.^4;

% squared centrifugal radius
rc2 = r2 + a2.*(1+2*u);
rc4 = rc2.^2;
rc  = sqrt(rc2);
drc = r./rc.*(1-a2.*u3);

D = r2-2.*r+a2;
dD = 2.*r -2;

% A function
Aeq  = (1-2./rc).*(1+2./rc)./(1+2./r);
dAeq = 2.*r2./rc4.*(1+2.*(r-2).*u3.*a2 + a4.*u4);

A = Aeq.*(1+dot(n,chi1).^2./r2)./(1+D.*dot(n,chi1).^2./(r2.*rc2));

% B function

Bp = 1./(1+dot(n,chi1).^2/r2);
Bnp = Bp.*(D./r2-1);
Benp = -Bp.*(r2+2.*r+dot(n,chi1).^2)./(r2.*rc2+D.*dot(n,chi1).^2);

% Gs function
Gs = 2.*r./(rc2.*r2+dot(chi1,n).^2*D);

%derivatives 

x = X(1);
y = X(2);
z = X(3);


dAdx = r.^(-1).*rc.*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).* ...
    z],chi1).^2).^(-2).*(dAeq.*rc.*x.*(r.^2+dot([r.^(-1).*x,r.^(-1).* ...
    y,r.^(-1).*z],chi1).^2).*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).* ...
    y,r.^(-1).*z],chi1).^2)+(-1).*Aeq.*dot([r.^(-1).*x,r.^(-1).*y,r.^( ...
    -1).*z],chi1).*(r.*((-2).*D.*drc.*r+(-2).*D.*rc+dD.*r.*rc+2.* ...
    rc.^3).*x.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1)+((-2).*D.* ...
    drc.*x+dD.*rc.*x).*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1) ...
    .^3+2.*r.^3.*rc.*(D+(-1).*rc.^2).*dot([r.^(-3).*(r.^2+(-1).*x.^2), ...
    (-1).*r.^(-3).*x.*y,(-1).*r.^(-3).*x.*z],chi1)));

dAdy = r.^(-1).*rc.*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).* ...
    z],chi1).^2).^(-2).*(dAeq.*rc.*y.*(r.^2+dot([r.^(-1).*x,r.^(-1).* ...
    y,r.^(-1).*z],chi1).^2).*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).* ...
    y,r.^(-1).*z],chi1).^2)+(-1).*Aeq.*dot([r.^(-1).*x,r.^(-1).*y,r.^( ...
    -1).*z],chi1).*(r.*((-2).*D.*drc.*r+(-2).*D.*rc+dD.*r.*rc+2.* ...
    rc.^3).*y.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1)+((-2).*D.* ...
    drc.*y+dD.*rc.*y).*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1) ...
    .^3+2.*r.^3.*rc.*(D+(-1).*rc.^2).*dot([(-1).*r.^(-3).*x.*y,r.^(-3) ...
    .*(r.^2+(-1).*y.^2),(-1).*r.^(-3).*y.*z],chi1)));

dAdz = r.^(-1).*rc.*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).* ...
    z],chi1).^2).^(-2).*(dAeq.*rc.*z.*(r.^2+dot([r.^(-1).*x,r.^(-1).* ...
    y,r.^(-1).*z],chi1).^2).*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).* ...
    y,r.^(-1).*z],chi1).^2)+(-1).*Aeq.*dot([r.^(-1).*x,r.^(-1).*y,r.^( ...
    -1).*z],chi1).*(r.*((-2).*D.*drc.*r+(-2).*D.*rc+dD.*r.*rc+2.* ...
    rc.^3).*z.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1)+((-2).*D.* ...
    drc.*z+dD.*rc.*z).*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1) ...
    .^3+2.*r.^3.*rc.*(D+(-1).*rc.^2).*dot([(-1).*r.^(-3).*x.*z,(-1).* ...
    r.^(-3).*y.*z,r.^(-3).*(r.^2+(-1).*z.^2)],chi1)));

dBpdx = 2.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).*(r.^2+dot([r.^( ...
    -1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^(-2).*(x.*dot([r.^(-1).* ...
    x,r.^(-1).*y,r.^(-1).*z],chi1)+(-1).*r.^2.*dot([r.^(-3).*(r.^2+( ...
    -1).*x.^2),(-1).*r.^(-3).*x.*y,(-1).*r.^(-3).*x.*z],chi1));

dBpdy = 2.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).*(r.^2+dot([r.^( ...
    -1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^(-2).*(y.*dot([r.^(-1).* ...
    x,r.^(-1).*y,r.^(-1).*z],chi1)+(-1).*r.^2.*dot([(-1).*r.^(-3).*x.* ...
    y,r.^(-3).*(r.^2+(-1).*y.^2),(-1).*r.^(-3).*y.*z],chi1));

dBpdz = 2.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).*(r.^2+dot([r.^( ...
    -1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^(-2).*(z.*dot([r.^(-1).* ...
    x,r.^(-1).*y,r.^(-1).*z],chi1)+(-1).*r.^2.*dot([(-1).*r.^(-3).*x.* ...
    z,(-1).*r.^(-3).*y.*z,r.^(-3).*(r.^2+(-1).*z.^2)],chi1));

dBnpdx = r.^(-1).*(r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^( ...
    -2).*(r.*((-2).*D+dD.*r).*x+(dD+(-2).*r).*x.*dot([r.^(-1).*x,r.^( ...
    -1).*y,r.^(-1).*z],chi1).^2+2.*r.*((-1).*D+r.^2).*dot([r.^(-1).*x, ...
    r.^(-1).*y,r.^(-1).*z],chi1).*dot([r.^(-3).*(r.^2+(-1).*x.^2),(-1) ...
    .*r.^(-3).*x.*y,(-1).*r.^(-3).*x.*z],chi1));

dBnpdy = r.^(-1).*(r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^( ...
    -2).*(r.*((-2).*D+dD.*r).*y+(dD+(-2).*r).*y.*dot([r.^(-1).*x,r.^( ...
    -1).*y,r.^(-1).*z],chi1).^2+2.*r.*((-1).*D+r.^2).*dot([r.^(-1).*x, ...
    r.^(-1).*y,r.^(-1).*z],chi1).*dot([(-1).*r.^(-3).*x.*y,r.^(-3).*( ...
    r.^2+(-1).*y.^2),(-1).*r.^(-3).*y.*z],chi1));

dBnpdz = r.^(-1).*(r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^( ...
    -2).*(r.*((-2).*D+dD.*r).*z+(dD+(-2).*r).*z.*dot([r.^(-1).*x,r.^( ...
    -1).*y,r.^(-1).*z],chi1).^2+2.*r.*((-1).*D+r.^2).*dot([r.^(-1).*x, ...
    r.^(-1).*y,r.^(-1).*z],chi1).*dot([(-1).*r.^(-3).*x.*z,(-1).*r.^( ...
    -3).*y.*z,r.^(-3).*(r.^2+(-1).*z.^2)],chi1));

dBenpdx = (r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^(-2).*( ...
    r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^( ...
    -2).*((-2).*r.*(r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1) ...
    .^2).*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1) ...
    .^2).*(x+r.*x+r.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).* ...
    dot([r.^(-3).*(r.^2+(-1).*x.^2),(-1).*r.^(-3).*x.*y,(-1).*r.^(-3) ...
    .*x.*z],chi1))+2.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).*( ...
    r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).*( ...
    (-1).*x.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1)+r.^2.*dot( ...
    [r.^(-3).*(r.^2+(-1).*x.^2),(-1).*r.^(-3).*x.*y,(-1).*r.^(-3).*x.* ...
    z],chi1)).*(r.^2+2.*(x.^2+y.^2+z.^2).^(1/2)+dot([x.*(x.^2+y.^2+ ...
    z.^2).^(-1/2),y.*(x.^2+y.^2+z.^2).^(-1/2),z.*(x.^2+y.^2+z.^2).^( ...
    -1/2)],chi1).^2)+r.*(r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z], ...
    chi1).^2).*(2.*drc.*r.^2.*rc.*x+2.*r.*rc.^2.*x+dot([r.^(-1).*x, ...
    r.^(-1).*y,r.^(-1).*z],chi1).*(dD.*x.*dot([r.^(-1).*x,r.^(-1).*y, ...
    r.^(-1).*z],chi1)+2.*D.*r.*dot([r.^(-3).*(r.^2+(-1).*x.^2),(-1).* ...
    r.^(-3).*x.*y,(-1).*r.^(-3).*x.*z],chi1))).*(r.^2+2.*(x.^2+y.^2+ ...
    z.^2).^(1/2)+dot([x.*(x.^2+y.^2+z.^2).^(-1/2),y.*(x.^2+y.^2+z.^2) ...
    .^(-1/2),z.*(x.^2+y.^2+z.^2).^(-1/2)],chi1).^2));

dBenpdy = (r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^(-2).*( ...
    r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^( ...
    -2).*((-2).*r.*(r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1) ...
    .^2).*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1) ...
    .^2).*(y+r.*y+r.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).* ...
    dot([(-1).*r.^(-3).*x.*y,r.^(-3).*(r.^2+(-1).*y.^2),(-1).*r.^(-3) ...
    .*y.*z],chi1))+2.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).*( ...
    r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).*( ...
    (-1).*y.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1)+r.^2.*dot([( ...
    -1).*r.^(-3).*x.*y,r.^(-3).*(r.^2+(-1).*y.^2),(-1).*r.^(-3).*y.* ...
    z],chi1)).*(r.^2+2.*(x.^2+y.^2+z.^2).^(1/2)+dot([x.*(x.^2+y.^2+ ...
    z.^2).^(-1/2),y.*(x.^2+y.^2+z.^2).^(-1/2),z.*(x.^2+y.^2+z.^2).^( ...
    -1/2)],chi1).^2)+r.*(r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z], ...
    chi1).^2).*(2.*drc.*r.^2.*rc.*y+2.*r.*rc.^2.*y+dot([r.^(-1).*x, ...
    r.^(-1).*y,r.^(-1).*z],chi1).*(dD.*y.*dot([r.^(-1).*x,r.^(-1).*y, ...
    r.^(-1).*z],chi1)+2.*D.*r.*dot([(-1).*r.^(-3).*x.*y,r.^(-3).*( ...
    r.^2+(-1).*y.^2),(-1).*r.^(-3).*y.*z],chi1))).*(r.^2+2.*(x.^2+ ...
    y.^2+z.^2).^(1/2)+dot([x.*(x.^2+y.^2+z.^2).^(-1/2),y.*(x.^2+y.^2+ ...
    z.^2).^(-1/2),z.*(x.^2+y.^2+z.^2).^(-1/2)],chi1).^2));

dBenpdz = (r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^(-2).*( ...
    r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).^( ...
    -2).*((-2).*r.*(r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1) ...
    .^2).*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1) ...
    .^2).*(z+r.*z+r.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).* ...
    dot([(-1).*r.^(-3).*x.*z,(-1).*r.^(-3).*y.*z,r.^(-3).*(r.^2+(-1).* ...
    z.^2)],chi1))+2.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).*( ...
    r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).^2).*( ...
    (-1).*z.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1)+r.^2.*dot([( ...
    -1).*r.^(-3).*x.*z,(-1).*r.^(-3).*y.*z,r.^(-3).*(r.^2+(-1).*z.^2) ...
    ],chi1)).*(r.^2+2.*(x.^2+y.^2+z.^2).^(1/2)+dot([x.*(x.^2+y.^2+ ...
    z.^2).^(-1/2),y.*(x.^2+y.^2+z.^2).^(-1/2),z.*(x.^2+y.^2+z.^2).^( ...
    -1/2)],chi1).^2)+r.*(r.^2+dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z], ...
    chi1).^2).*(2.*drc.*r.^2.*rc.*z+2.*r.*rc.^2.*z+dot([r.^(-1).*x, ...
    r.^(-1).*y,r.^(-1).*z],chi1).*(dD.*z.*dot([r.^(-1).*x,r.^(-1).*y, ...
    r.^(-1).*z],chi1)+2.*D.*r.*dot([(-1).*r.^(-3).*x.*z,(-1).*r.^(-3) ...
    .*y.*z,r.^(-3).*(r.^2+(-1).*z.^2)],chi1))).*(r.^2+2.*(x.^2+y.^2+ ...
    z.^2).^(1/2)+dot([x.*(x.^2+y.^2+z.^2).^(-1/2),y.*(x.^2+y.^2+z.^2) ...
    .^(-1/2),z.*(x.^2+y.^2+z.^2).^(-1/2)],chi1).^2));


dGsdx = (-2).*r.^(-1).*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1) ...
    .*z],chi1).^2).^(-2).*(2.*drc.*r.^3.*rc.*x+r.^2.*rc.^2.*x+dot( ...
    [r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).*(((-1).*D.*x+dD.*r.*x).* ...
    dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1)+2.*D.*r.^2.*dot([r.^( ...
    -3).*(r.^2+(-1).*x.^2),(-1).*r.^(-3).*x.*y,(-1).*r.^(-3).*x.*z], ...
    chi1)));

dGsdy = (-2).*r.^(-1).*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1) ...
    .*z],chi1).^2).^(-2).*(2.*drc.*r.^3.*rc.*y+r.^2.*rc.^2.*y+dot( ...
    [r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).*(((-1).*D.*y+dD.*r.*y).* ...
    dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1)+2.*D.*r.^2.*dot([(-1) ...
    .*r.^(-3).*x.*y,r.^(-3).*(r.^2+(-1).*y.^2),(-1).*r.^(-3).*y.*z], ...
    chi1)));

dGsdz = (-2).*r.^(-1).*(r.^2.*rc.^2+D.*dot([r.^(-1).*x,r.^(-1).*y,r.^(-1) ...
    .*z],chi1).^2).^(-2).*(2.*drc.*r.^3.*rc.*z+r.^2.*rc.^2.*z+dot( ...
    [r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1).*(((-1).*D.*z+dD.*r.*z).* ...
    dot([r.^(-1).*x,r.^(-1).*y,r.^(-1).*z],chi1)+2.*D.*r.^2.*dot([(-1) ...
    .*r.^(-3).*x.*z,(-1).*r.^(-3).*y.*z,r.^(-3).*(r.^2+(-1).*z.^2)], ...
    chi1)));

dA.dx = [dAdx;dAdy;dAdz];

