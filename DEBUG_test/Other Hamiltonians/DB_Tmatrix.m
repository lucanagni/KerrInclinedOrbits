        .*((-1)+xi).*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))+(-1).*dxidz.*z.*( ...
        r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)));x.*y.*(r.^2+((-1)+xi).*(x.^2+ ...
