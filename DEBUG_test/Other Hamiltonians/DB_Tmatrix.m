        xi).*(x.^2+y.^2+z.^2))+(-1).*dxidz.*z.*(r.^2+((-1)+xi).*(x.^2+ ...
        y.^2+z.^2)));x.*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)).^(-2).*(((-1)+ ...
        xi).*z.*(dxidz.*r.^2+2.*xi.*z)+(-1).*((-1)+xi).*(r.^2+((-1)+xi).*( ...
