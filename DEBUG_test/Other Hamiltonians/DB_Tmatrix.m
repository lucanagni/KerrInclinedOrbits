        xi.*z).*(r.^2+((-1)+xi).*(y.^2+z.^2))+(2.*xi.*z+dxidz.*(y.^2+z.^2) ...
        ).*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))),x.*y.*(r.^2+((-1)+xi).*( ...
        x.^2+y.^2+z.^2)).^(-2).*(((-1)+xi).*(dxidz.*r.^2+2.*xi.*z)+(-1).* ...
        dxidz.*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))),x.*(r.^2+((-1)+xi).*( ...
