        -2).*((-1).*(dxidy.*r.^2+2.*xi.*y).*(r.^2+((-1)+xi).*(x.^2+z.^2))+ ...
        (2.*y+dxidy.*(x.^2+z.^2)).*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))),z.* ...
        (r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)).^(-2).*(((-1)+xi).*y.*(dxidy.* ...
        r.^2+2.*xi.*y)+(-1).*((-1)+xi).*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)) ...
        +(-1).*dxidy.*y.*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)));x.*z.*(r.^2+( ...
        (-1)+xi).*(x.^2+y.^2+z.^2)).^(-2).*(((-1)+xi).*(dxidy.*r.^2+2.* ...
        xi.*y)+(-1).*dxidy.*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))),z.*(r.^2+( ...
        (-1)+xi).*(x.^2+y.^2+z.^2)).^(-2).*(((-1)+xi).*y.*(dxidy.*r.^2+2.* ...
        xi.*y)+(-1).*((-1)+xi).*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))+(-1).* ...
        dxidy.*y.*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))),(r.^2+((-1)+xi).*( ...
