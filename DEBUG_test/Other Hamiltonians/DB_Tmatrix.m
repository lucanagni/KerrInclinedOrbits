        y.^2+z.^2))),(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)).^(-2).*((-1).*( ...
        dxidx.*r.^2+2.*x.*xi).*(r.^2+((-1)+xi).*(x.^2+z.^2))+(2.*x.*xi+ ...
        dxidx.*(x.^2+z.^2)).*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))),y.*z.*( ...
        r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)).^(-2).*(((-1)+xi).*(dxidx.*r.^2+ ...
        2.*x.*xi)+(-1).*dxidx.*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)));z.*( ...
        r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)).^(-2).*(x.*((-1)+xi).*(dxidx.* ...
        r.^2+2.*x.*xi)+(-1).*dxidx.*x.*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))+ ...
        (-1).*((-1)+xi).*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))),y.*z.*(r.^2+( ...
        (-1)+xi).*(x.^2+y.^2+z.^2)).^(-2).*(((-1)+xi).*(dxidx.*r.^2+2.*x.* ...
        xi)+(-1).*dxidx.*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))),(r.^2+((-1)+ ...
        xi).*(x.^2+y.^2+z.^2)).^(-2).*((-1).*(dxidx.*r.^2+2.*x.*xi).*( ...
        r.^2+((-1)+xi).*(x.^2+y.^2))+(2.*x.*xi+dxidx.*(x.^2+y.^2)).*(r.^2+ ...
        ((-1)+xi).*(x.^2+y.^2+z.^2)))];

    dTinvdy = [(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2)).^(-2).*((-1).*(dxidy.*r.^2+2.* ...
        xi.*y).*(r.^2+((-1)+xi).*(y.^2+z.^2))+(2.*xi.*y+dxidy.*(y.^2+z.^2) ...
        ).*(r.^2+((-1)+xi).*(x.^2+y.^2+z.^2))),x.*(r.^2+((-1)+xi).*(x.^2+ ...
